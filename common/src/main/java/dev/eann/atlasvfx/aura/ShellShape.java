package dev.eann.atlasvfx.aura;

/** The form a shell of light round a body takes. */
public enum ShellShape {
    /** A ball round the middle of the body. */
    SPHERE,
    /** Half a ball standing on the ground over the body: a ward. */
    DOME,
    /** A column standing on the ground, fading out at its top. */
    CYLINDER
}
